export function hasCompleteLegalOperator(operator = LEGAL_OPERATOR) {
  return Object.values(operator).every((value) => value && !String(value).includes("["));
}

/** @param {Partial<typeof LEGAL_OPERATOR>} [overrides] */
export function resolveLegalBundle(overrides = {}) {
  const operator = {
    name: String(overrides.name || LEGAL_OPERATOR.name).trim(),
    status: String(overrides.status || LEGAL_OPERATOR.status).trim(),
    inn: String(overrides.inn || LEGAL_OPERATOR.inn).trim(),
    ogrn: String(overrides.ogrn || LEGAL_OPERATOR.ogrn).trim(),
    address: String(overrides.address || LEGAL_OPERATOR.address).trim(),
    email: String(overrides.email || LEGAL_OPERATOR.email).trim(),
  };
  const replacements = [
    [LEGAL_OPERATOR.name, operator.name],
    [LEGAL_OPERATOR.status, operator.status],
    [LEGAL_OPERATOR.inn, operator.inn],
    [LEGAL_OPERATOR.ogrn, operator.ogrn],
    [LEGAL_OPERATOR.address, operator.address],
    [LEGAL_OPERATOR.email, operator.email],
  ];
  /** @param {string} value */
  const replaceOperator = (value) => replacements.reduce(
    (text, [placeholder, replacement]) => text.replaceAll(placeholder, replacement),
    String(value),
  );
  const docs = LEGAL_DOCS.map((doc) => ({
    ...doc,
    summary: replaceOperator(doc.summary),
    sections: doc.sections.map(([title, body]) => [title, replaceOperator(body)]),
  }));
  return {
    version: LEGAL_VERSION,
    operator,
    operatorComplete: hasCompleteLegalOperator(operator),
    docs,
  };
}
